// ── Goal achievement helpers ──────────────────────────────────────────────────
type GoalResult = {
  label: string;
  metric: string;
  curr: number;
  prev: number | null;
  unit: string;
  invert: boolean; // lower is better
};

function buildGoalResult(goalData: any, session: any, prevSessions: any[]): GoalResult | null {
  if (!goalData) return null;
  const prev = prevSessions.length > 1 ? prevSessions[1] : null;
  const { metric, label } = goalData;

  const mappings: Record<string, { curr: number; prev: number | null; unit: string; invert: boolean }> = {
    fillers:     { curr: session.filler_words_count || 0, prev: prev?.filler_words_count ?? null, unit: " words", invert: true },
    eye_contact: { curr: Math.round((session.eye_contact_score || 0) * 100), prev: prev ? Math.round((prev.eye_contact_score || 0) * 100) : null, unit: "%", invert: false },
    posture:     { curr: Math.round(((session.posture_score || 0) / 10) * 100), prev: prev ? Math.round(((prev.posture_score || 0) / 10) * 100) : null, unit: "%", invert: false },
    gestures:    { curr: Math.round(((session.gesture_score || 0) / 15) * 100), prev: prev ? Math.round(((prev.gesture_score || 0) / 15) * 100) : null, unit: "%", invert: false },
    content:     { curr: Math.round(((session.content_score || 0) / 30) * 100), prev: prev ? Math.round(((prev.content_score || 0) / 30) * 100) : null, unit: "%", invert: false },
    pace:        { curr: session.pacing_wpm || 120, prev: null, unit: " WPM", invert: false },
    overall:     { curr: Math.round(session.overall_score || 0), prev: prev ? Math.round(prev.overall_score || 0) : null, unit: "/100", invert: false },
  };

  const m = mappings[metric] ?? mappings.overall;
  return { label, metric, ...m };
}

